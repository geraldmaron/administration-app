import { fileURLToPath } from "node:url";
import { expect, test } from "@playwright/test";
import { confirmReview, expectNoHorizontalOverflow } from "./helpers";

for (const theme of ["light", "dark"] as const) {
  test(`allocation, exact signature and contextual emergency action · ${theme}`, async ({ page }, info) => {
    await page.emulateMedia({ colorScheme: theme, reducedMotion: "reduce" });
    await page.goto("/administrations");
    await page.getByLabel("Import a save exported from this game").setInputFiles(fileURLToPath(new URL("./.fixtures/hurricane-request.json", import.meta.url)));
    await page.waitForURL("**/brief", { timeout: 60_000 });
    await page.goto("/nation/budget");
    await expect(page.getByRole("region", { name: "Allocation by line" })).toBeVisible();
    const defense = page.getByRole("slider", { name: "Defense establishment" });
    await defense.focus();
    await defense.press("ArrowRight");
    await expect(page.locator(".alloc[data-moved='true']")).toHaveCount(1);
    await expect(page.getByRole("complementary", { name: "Consequences of the proposed allocation" })).toContainText("Material tradeoffs");
    await expectNoHorizontalOverflow(page, "budget allocation and consequences");
    await page.getByRole("heading", { name: "Allocation by line", exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: info.outputPath(`budget-${theme}.png`), fullPage: true, animations: "disabled" });
    await page.getByRole("tab", { name: "Budget authority", exact: true }).click();
    await expectNoHorizontalOverflow(page, "budget authority");
    await page.getByRole("tab", { name: "Federal books", exact: true }).click();
    await expectNoHorizontalOverflow(page, "federal books");
    await page.goto("/nation/policy?view=orders");
    await expect(page.getByRole("tab", { name: /Order catalogue/ })).toBeVisible();
    await page.getByRole("link", { name: "Turn federal purchasing to clean power", exact: true }).click();
    const authorization = page.getByRole("region", { name: "Authorization" }).last();
    await authorization.getByRole("radio", { name: "Sign the order", exact: true }).check();
    await page.getByRole("button", { name: "Sign the order", exact: true }).click();
    await confirmReview(page);
    await expect(page.getByRole("article", { name: "Signed: Turn federal purchasing to clean power" })).toBeVisible({ timeout: 30_000 });
    await page.goto("/nation/policy?view=orders");
    await expect(page.getByRole("tab", { name: /Issued signatures/ })).toHaveAttribute("aria-selected", "true");
    const orderSearch = page.getByRole("searchbox", { name: "Find an executive order", exact: true });
    await orderSearch.fill("clean power");
    await expect.poll(() => new URL(page.url()).searchParams.get("orderQuery")).toBe("clean power");
    await page.reload();
    await expect(orderSearch).toHaveValue("clean power");
    await expectNoHorizontalOverflow(page, "order collection");
    await page.screenshot({ path: info.outputPath(`orders-${theme}.png`), fullPage: true, animations: "disabled" });
    await page.getByRole("link", { name: "Turn federal purchasing to clean power", exact: true }).click();
    await expect(page).toHaveURL(/\?record=/);
    const signature = page.getByRole("dialog", { name: "Signed order record", exact: true });
    await expect(signature).toContainText("Signature reference");
    await expect(signature).toContainText("Complete historical terms are not reconstructed");
    await expectNoHorizontalOverflow(page, "signed order record");
    await page.screenshot({ path: info.outputPath(`signature-${theme}.png`), fullPage: true, animations: "disabled" });
    await signature.getByRole("button", { name: "Close", exact: true }).click();
    await expect(page).not.toHaveURL(/record=/);
    await page.goBack();
    await expect(page.getByRole("searchbox", { name: "Find an executive order", exact: true })).toHaveValue("clean power");
    await page.getByRole("tab", { name: /^Proposals/ }).click();
    await expect(page.getByRole("heading", { name: "Fiscal", exact: true })).toBeVisible();
    const domainPicker = page.getByRole("combobox", { name: "Policy domain", exact: true });
    if (await domainPicker.isVisible()) {
      await domainPicker.selectOption("trade");
      await expect(page.getByRole("heading", { name: "Trade", exact: true })).toBeVisible();
      await page.getByRole("button", { name: "Compare portfolios", exact: true }).click();
      const portfolios = page.getByRole("dialog", { name: "Policy portfolio comparison", exact: true });
      await expect(portfolios.getByRole("link")).toHaveCount(6);
      await portfolios.getByRole("link", { name: /^Fiscal/ }).click();
      await expect(portfolios).toHaveCount(0);
      await expect(domainPicker).toHaveValue("fiscal");
    }
    await expectNoHorizontalOverflow(page, "policy proposals");
    await page.screenshot({ path: info.outputPath(`policy-${theme}.png`), fullPage: true, animations: "disabled" });
    await page.getByRole("tab", { name: "Implementation", exact: true }).click();
    await expectNoHorizontalOverflow(page, "policy implementation");
    await page.screenshot({ path: info.outputPath(`implementation-${theme}.png`), fullPage: true, animations: "disabled" });
    await page.goto("/nation/emergency");
    await expect(page.getByRole("heading", { name: /^Response: / })).toBeVisible();
    await expectNoHorizontalOverflow(page, "incident workspace");
    await page.screenshot({ path: info.outputPath(`emergency-${theme}.png`), fullPage: true, animations: "disabled" });
    const declare = page.getByRole("button", { name: "Declare an emergency", exact: true }).first();
    await declare.click();
    const action = page.getByRole("dialog", { name: "Presidential emergency action", exact: true });
    await expect(action.getByRole("region", { name: "Compare against doing nothing", exact: true })).toBeVisible();
    await expect(action.getByRole("radio", { name: "Don't declare", exact: true })).toBeChecked();
    await expect(action.getByRole("button", { name: "Declare the emergency", exact: true })).toBeDisabled();
    await expectNoHorizontalOverflow(page, "emergency action sheet");
    await page.screenshot({ path: info.outputPath(`emergency-action-${theme}.png`), fullPage: true, animations: "disabled" });
    await action.getByRole("button", { name: "Close", exact: true }).click();
    await expect(declare).toBeFocused();
  });
}
