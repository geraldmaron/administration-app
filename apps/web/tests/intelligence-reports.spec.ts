import { expect, test } from "@playwright/test";
import { confirmReview, importFixture, expectNoHorizontalOverflow } from "./helpers";

test("read, share and retain a dated intelligence report through the player", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await importFixture(page, "collection-intelligence");
  await page.goto("/world/security?view=intelligence");
  const reports = page.getByRole("region", { name: "Intelligence reports", exact: true });
  await expect(reports).toBeVisible();
  const foreign = reports.getByRole("listitem").filter({ has: page.getByRole("heading", { name: /^Russia\s*:/ }) });
  await expect(foreign).toContainText("Source confidence:");
  await foreign.getByRole("button", { name: "Sources, gaps and sharing", exact: true }).click();
  const inspector = page.getByRole("dialog", { name: "Russia: report limitations and sharing", exact: true });
  await expect(inspector).toContainText("Kept within the administration");
  await page.keyboard.press("Escape");
  await expect(inspector).toBeHidden();
  await expect(foreign.getByRole("button", { name: "Sources, gaps and sharing", exact: true })).toBeFocused();
  await expect(reports).toContainText("Minnesota");
  await expect(reports).toContainText("DHS I&A files");
  await expect(reports).not.toContainText("What did federal surveillance obtain?");
  await expectNoHorizontalOverflow(page, "intelligence reports");
  await page.screenshot({ path: info.outputPath(`intelligence-reports-${info.project.name}.png`), fullPage: true });
  await foreign.getByRole("button", { name: "Review sharing" }).click();
  await page.getByLabel("Recipient government").selectOption("CAN");
  await page.getByRole("radio", { name: "Share this report", exact: true }).check();
  await page.getByRole("checkbox").first().check();
  await expect(page.getByRole("button", { name: "Send this report", exact: true })).toBeEnabled();
  await expectNoHorizontalOverflow(page, "intelligence sharing");
  await page.screenshot({ path: info.outputPath(`intelligence-sharing-${info.project.name}.png`), fullPage: true });
  await page.getByRole("button", { name: "Send this report", exact: true }).click();
  await confirmReview(page);
  await expect(page.getByRole("article", { name: "Intelligence shared with Canada", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Back to the desk", exact: true }).click();
  await foreign.getByRole("button", { name: "Sources, gaps and sharing", exact: true }).click();
  await expect(inspector).toContainText("Shared 1 finding with Canada");
  await page.reload();
  await foreign.getByRole("button", { name: "Sources, gaps and sharing", exact: true }).click();
  await expect(inspector).toContainText("Shared 1 finding with Canada");
  expect(errors).toEqual([]);
});
