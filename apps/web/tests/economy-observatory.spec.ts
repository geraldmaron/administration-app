import { fileURLToPath } from "node:url";
import { expect, test } from "@playwright/test";
import { expectNoHorizontalOverflow, selectChoice } from "./helpers";

for (const theme of ["light", "dark"] as const) {
  test(`economic signals share benchmark axes, context and evidence · ${theme}`, async ({ page }, info) => {
    await page.emulateMedia({ colorScheme: theme, reducedMotion: "reduce" });
    await page.goto("/administrations");
    await page.getByLabel("Import a save exported from this game").setInputFiles(fileURLToPath(new URL("./.fixtures/gulf-oil-shock.json", import.meta.url)));
    await page.waitForURL("**/brief");
    await page.goto("/nation/economy");
    await expect(page.locator(".economic-signal")).toHaveCount(3);
    const boxes = await page.locator(".economic-signal__value").evaluateAll((elements) => elements.map((element) => { const box = element.getBoundingClientRect(); return { top: box.top, right: box.right }; }));
    const alignment = (page.viewportSize()?.width ?? 1440) <= 352 ? boxes.map((box) => box.right) : boxes.map((box) => box.top);
    expect(Math.max(...alignment) - Math.min(...alignment), "signal values align within their responsive composition").toBeLessThan(1);
    const plot = page.locator(".economic-comparison .sc__plot");
    await expect(plot.locator("svg")).toHaveCount(1);
    await expect(plot.locator(".sc__line[data-tone='reference']")).toHaveCount(1);
    await expect(plot.locator(".sc__line[data-tone='played']")).toHaveCount(1);
    await expect(page.getByRole("figure", { name: /^Unemployment, 2017/ })).toBeVisible();
    await expect(page.locator(".economic-benchmarks")).toContainText("Current weekly");
    await expect(page.locator(".economic-benchmarks")).toContainText("not a policy target");
    await expectNoHorizontalOverflow(page, "inline economic benchmark");
    await page.screenshot({ path: info.outputPath(`economy-entry-after-${theme}.png`), fullPage: true, animations: "disabled" });
    await page.locator(".economic-observatory").evaluate((element) => element.scrollIntoView({ block: "start" }));
    await page.screenshot({ path: info.outputPath(`economy-after-${theme}.png`), fullPage: true, animations: "disabled" });
    await page.locator(".economic-signal").filter({ hasText: "Inflation" }).click();
    await expect(page).toHaveURL(/measure=inflation/);
    await expect(page.getByRole("figure", { name: /^Inflation, 2017/ })).toBeVisible();
    await expect(page.getByText("Approximate comparison", { exact: true })).toBeVisible();
    await expect(page.locator(".economic-drivers")).toContainText("Inflation");
    await page.getByRole("button", { name: "Method & comparability", exact: true }).click();
    const method = page.getByRole("dialog", { name: "Inflation: comparison method", exact: true });
    await expect(method).toContainText("twelve-month change");
    await method.getByRole("button", { name: "Close", exact: true }).click();
    await page.getByRole("combobox", { name: "Historical US window", exact: true }).selectOption("2020-2022");
    await expect(page).toHaveURL(/comparisonWindow=2020-2022/);
    await page.reload();
    await expect(page.getByRole("combobox", { name: "Historical US window", exact: true })).toHaveValue("2020-2022");
    await expect(page.getByRole("figure", { name: /^Inflation, 2020/ })).toBeVisible();
    await selectChoice(page, "Evidence basis", "Observed history");
    await expect(page.getByRole("figure", { name: /^Inflation.*this administration/ })).toBeVisible();
    await page.getByRole("button", { name: "Source & interpretation", exact: true }).click();
    const source = page.getByRole("dialog", { name: /Inflation.*source and interpretation/ });
    await expect(source).toContainText("Bureau of Labor Statistics");
    await source.getByRole("button", { name: "Close", exact: true }).click();
    await selectChoice(page, "History window", "Published context");
    await page.getByRole("button", { name: /^Inspect \d+ observations$/ }).click();
    const observations = page.getByRole("dialog", { name: /Inflation.*recorded observations/ });
    await expect(observations.getByRole("row", { name: "Unobserved bridge before the oath Unknown", exact: true })).toBeVisible();
    await observations.getByRole("button", { name: "Close", exact: true }).click();
    await selectChoice(page, "Evidence basis", "Countries");
    await expect(page).toHaveURL(/basis=countries/);
    await expect(page.locator(".economic-comparison")).toContainText("real countries");
    await expect(page.getByRole("figure", { name: /^Inflation, 2007/ })).toBeVisible();
    await expect(page.locator(".economic-benchmarks")).toContainText("Current weekly");
    await page.reload();
    await expect(page.getByRole("figure", { name: /^Inflation, 2007/ })).toBeVisible();
    await page.locator(".compare__chips input:checked").nth(1).uncheck();
    await expect(page).toHaveURL(/peers=/);
    await expect(page.locator(".compare__chips input:checked")).toHaveCount(2);
    await page.getByRole("radio", { name: "2015–2019", exact: true }).check();
    await expect(page).toHaveURL(/peerWindow=2015-2019/);
    await page.reload();
    await expect(page.getByRole("figure", { name: /^Inflation, 2015/ })).toBeVisible();
    await expect(page.locator(".compare__chips input:checked")).toHaveCount(2);
    await page.goBack();
    await expect(page.getByRole("figure", { name: /^Inflation, 2007/ })).toBeVisible();
    await expect(page.locator(".compare__chips input:checked")).toHaveCount(2);
    await page.goBack();
    await expect(page.locator(".compare__chips input:checked")).toHaveCount(3);
    await page.goForward();
    await page.goForward();
    await expect(page.getByRole("figure", { name: /^Inflation, 2015/ })).toBeVisible();
    await selectChoice(page, "Evidence basis", "Observed history");
    await selectChoice(page, "Evidence basis", "Countries");
    await expect(page.getByRole("figure", { name: /^Inflation, 2015/ })).toBeVisible();
    await expect(page.locator(".compare__chips input:checked")).toHaveCount(2);
    await expectNoHorizontalOverflow(page, "selected-rate international reference");
    await page.locator(".economic-evidence").evaluate((element) => element.scrollIntoView({ block: "start" }));
    await page.screenshot({ path: info.outputPath(`economy-country-context-${theme}.png`), animations: "disabled" });
    await page.getByRole("figure", { name: /^Inflation, 2015/ }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: info.outputPath(`economy-country-chart-${theme}.png`), animations: "disabled" });
  });

  test(`opening Economy keeps benchmarks visible without inventing a monthly result · ${theme}`, async ({ page }, info) => {
    await page.emulateMedia({ colorScheme: theme, reducedMotion: "reduce" });
    await page.goto("/administrations");
    await page.getByLabel("Import a save exported from this game").setInputFiles(fileURLToPath(new URL("./.fixtures/opening.json", import.meta.url)));
    await page.waitForURL("**/brief");
    await page.goto("/nation/economy");
    await expect(page.getByRole("figure", { name: /^Unemployment, 2017/ })).toBeVisible();
    await expect(page.locator(".sc__plot [data-tone='played']")).toHaveCount(0);
    await expect(page.getByText(/Your monthly comparison starts after a full month/)).toBeVisible();
    await expect(page.locator(".economic-benchmarks dd")).toHaveCount(3);
    await selectChoice(page, "Evidence basis", "Observed history");
    const published = page.getByRole("figure", { name: /^Unemployment, published and since the oath/ });
    await expect(published).toBeVisible();
    await expect(page).not.toHaveURL(/historyWindow=/);
    await expectNoHorizontalOverflow(page, "opening observed evidence");
    await page.locator(".economic-observatory").evaluate((element) => element.scrollIntoView({ block: "start" }));
    await page.screenshot({ path: info.outputPath(`economy-opening-published-${theme}.png`), fullPage: true, animations: "disabled" });
    await selectChoice(page, "History window", "This administration");
    await expect(page).toHaveURL(/historyWindow=term/);
    await expect(page.getByText("No weekly observation has been recorded in this administration.", { exact: true })).toBeVisible();
    await expect(page.locator(".economic-history .ui-series")).toHaveCount(0);
    await page.reload();
    await expect(page).toHaveURL(/historyWindow=term/);
    await expect(page.getByText("No weekly observation has been recorded in this administration.", { exact: true })).toBeVisible();
    await selectChoice(page, "Evidence basis", "US record");
    await expect(page.getByRole("figure", { name: /^Unemployment, 2017/ })).toBeVisible();
    await page.goto("/nation/economy?measure=growth&basis=us-record");
    await expect(page.getByText(/Your quarterly comparison starts after a full quarter/)).toBeVisible();
    await expect(page.locator(".sc__plot [data-tone='played']")).toHaveCount(0);
    await page.goto("/nation/economy?measure=inflation&basis=us-record&comparisonWindow=1973-1982");
    await expect(page.getByText(/This stretch can't be drawn:/)).toBeVisible();
    await expect(page.locator(".economic-comparison .sc")).toHaveCount(0);
    await expect(page.locator(".economic-benchmarks dd")).toHaveCount(3);
    await expectNoHorizontalOverflow(page, "explicit unavailable comparison");
  });
  test(`completed-quarter Growth shares axes and retains its subject through evidence bases · ${theme}`, async ({ page }, info) => {
    await page.emulateMedia({ colorScheme: theme, reducedMotion: "reduce" });
    await page.goto("/administrations");
    await page.getByLabel("Import a save exported from this game").setInputFiles(fileURLToPath(new URL("./.fixtures/week-30.json", import.meta.url)));
    await page.waitForURL("**/brief");
    await page.goto("/nation/economy?measure=growth&basis=us-record");
    const chart = page.getByRole("figure", { name: /^Growth, 2017/ });
    await expect(chart).toBeVisible();
    await expect(chart.locator(".sc__plot svg")).toHaveCount(1);
    await expect(chart.locator(".sc__line[data-tone='reference']")).toHaveCount(1);
    await expect(chart.locator(".sc__line[data-tone='played']")).toHaveCount(1);
    await expect(page.getByText("Quarterly comparison", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Method & comparability", exact: true }).click();
    const method = page.getByRole("dialog", { name: "Growth: comparison method", exact: true });
    await expect(method).not.toContainText("Your inflation");
    await expect(method).toContainText("Months since each began");
    await method.getByRole("button", { name: "Close", exact: true }).click();
    await expect(page.locator(".economic-benchmarks dd")).toHaveCount(3);
    await expectNoHorizontalOverflow(page, "completed-quarter Growth comparison");
    await page.screenshot({ path: info.outputPath(`economy-growth-entry-${theme}.png`), fullPage: true, animations: "disabled" });
    await chart.scrollIntoViewIfNeeded();
    await page.screenshot({ path: info.outputPath(`economy-growth-comparison-${theme}.png`), fullPage: true, animations: "disabled" });
    await selectChoice(page, "Evidence basis", "Countries");
    await expect(page.getByRole("figure", { name: /^Growth, 2007/ })).toBeVisible();
    await expect(page).toHaveURL(/measure=growth/);
    await selectChoice(page, "Evidence basis", "Observed history");
    await expect(page.getByRole("figure", { name: /^Growth.*this administration/ })).toBeVisible();
    await page.reload();
    await expect(page.getByRole("figure", { name: /^Growth.*this administration/ })).toBeVisible();
    await expect(page).toHaveURL(/measure=growth/);
    await selectChoice(page, "Evidence basis", "US record");
    await expect(chart.locator(".sc__line[data-tone='played']")).toHaveCount(1);
    await page.reload();
    await expect(chart.locator(".sc__line[data-tone='reference']")).toHaveCount(1);
    await expect(chart.locator(".sc__line[data-tone='played']")).toHaveCount(1);
  });

}
